void USART1_unpack(uint8_t res)
{
	static int state=0;
	static int len=1;
	static uint8_t data[6]={0};
	if(state==0 && res==0xaa)
	{
		state=1;
	}
	else if(state==1)
	{
		data[len++] = res;
		if(len >= 6)
			state = 2;
	}
	
	else if(res == 0xbb)
	{
		//USART1_RX_DATA[is_effect]=1;
		for(int i=1;i<6;i++)
		{
			USART1_RX_DATA[i-1] = data[i];
		}
		state=0;
		len=1;
		
	}
	else
	{
		state=0;                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                           
		len=1;
	}
}

